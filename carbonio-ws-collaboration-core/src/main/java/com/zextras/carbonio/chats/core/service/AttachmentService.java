package com.zextras.carbonio.chats.core.service;

import com.zextras.carbonio.chats.core.data.entity.FileMetadata;
import com.zextras.carbonio.chats.core.data.entity.Message;
import com.zextras.carbonio.chats.core.data.model.AttachmentFilter;
import com.zextras.carbonio.chats.core.data.model.AttachmentsPage;
import com.zextras.carbonio.chats.core.data.model.BulkDeleteResult;
import com.zextras.carbonio.chats.core.data.model.FileContentAndMetadata;
import com.zextras.carbonio.chats.core.web.security.UserPrincipal;
import jakarta.annotation.Nullable;
import java.io.InputStream;
import java.util.List;
import java.util.UUID;

public interface AttachmentService {

  /**
   * Gets a room's attachment
   *
   * @param fileId identifier of attachment file to delete {@link UUID}
   * @param currentUser current authenticated user {@link UserPrincipal}
   * @return Content and meta data of yhe attachment file requested {@link FileContentAndMetadata}
   */
  FileContentAndMetadata getAttachmentById(UUID fileId, UserPrincipal currentUser);

  /**
   * Retrieves paged list of metadata of every attachment uploaded to the room and the cursor for
   * the next page
   *
   * @param roomId room identifier {@link UUID}
   * @param limit maximum number of items to return per page
   * @param cursor opaque base64-encoded pagination token from the previous response
   * @param attachmentFilter optional field filters and sort options {@link AttachmentFilter}
   * @param currentUser current authenticated user {@link UserPrincipal}
   * @return paged list of attachments metadata, next cursor, and total matching attachment count
   *     for the requested room
   */
  AttachmentsPage getAttachmentInfoByRoomId(
      UUID roomId,
      Integer limit,
      @Nullable String cursor,
      @Nullable AttachmentFilter attachmentFilter,
      UserPrincipal currentUser);

  /**
   * Retrieves info related to an uploaded attachment
   *
   * @param fileId file identifier {@link UUID}
   * @param currentUser current authenticated user {@link UserPrincipal}
   * @return Attachment information {@link FileMetadata}
   */
  FileMetadata getAttachmentInfoById(UUID fileId, UserPrincipal currentUser);

  /**
   * Retrieves the metadata of the given files in a single query. No membership check is performed:
   * the caller derives the ids from items the user can already see.
   *
   * @param fileIds file identifiers
   * @return the {@link FileMetadata} found
   */
  List<FileMetadata> getAttachmentsInfoByIds(List<String> fileIds);

  /**
   * Saves a room's attachment file. The caller has already verified that the user is a member of
   * the room and that the reply target, if any, is visible to the user; no membership or reply
   * check is made here.
   *
   * @param roomId identifier of the room attachment {@link UUID}
   * @param file file stream to save {@link InputStream}
   * @param mimeType file mime type
   * @param contentLength file content length
   * @param fileName file name
   * @param description file description
   * @param replyId identifier of the message being replied to
   * @param area attachment's area
   * @param tempId client-generated temporary identifier for optimistic UI matching
   * @param messageId identifier of the message to create, generated by the caller
   * @param currentUser current authenticated user {@link UserPrincipal}
   * @return The created message (with attachmentId, metadata, and WS event already broadcast)
   *     {@link Message}
   */
  Message addAttachment(
      UUID roomId,
      InputStream file,
      String mimeType,
      Long contentLength,
      String fileName,
      String description,
      @Nullable String replyId,
      @Nullable String area,
      @Nullable String tempId,
      String messageId,
      UserPrincipal currentUser);

  /**
   * Deletes a room's attachment file
   *
   * @param fileId identifier of attachment file to delete {@link UUID}
   * @param currentUser current authenticated user {@link UserPrincipal}
   */
  void deleteAttachment(UUID fileId, UserPrincipal currentUser);

  /**
   * Deletes the attachments with the given identifiers: the stored files first, then the metadata
   * of the files that were really deleted from the storage, then their video previews. Failures are
   * logged, not propagated.
   *
   * @param attachmentIds attachment identifiers
   * @param currentUser current authenticated user {@link UserPrincipal}
   */
  void deleteAttachmentsByIds(List<String> attachmentIds, UserPrincipal currentUser);

  /**
   * Deletes the stored files of attachments whose metadata has already been deleted, and their
   * video previews. Failures are logged, not propagated.
   *
   * @param fileIds attachment identifiers
   * @param currentUser current authenticated user {@link UserPrincipal}
   */
  void deleteAttachmentFiles(List<String> fileIds, UserPrincipal currentUser);

  /**
   * Bulk deletes a list of attachments scoped to a specific room. The requesting user must be a
   * room member and must own each attachment. Partial success is supported: attachments that fail
   * to delete from storage keep their metadata and can be retried.
   *
   * @param roomId room identifier {@link UUID}
   * @param fileIds list of attachment file identifiers to delete {@link UUID}
   * @param currentUser current authenticated user {@link UserPrincipal}
   * @return result containing successfully deleted and failed attachment identifiers
   */
  BulkDeleteResult bulkDeleteRoomAttachments(
      UUID roomId, List<UUID> fileIds, UserPrincipal currentUser);

  /**
   * Copies the preview frame of a video attachment to its copy in the preview service, off the
   * request thread; a missing source preview or any failure is ignored (the copy's preview is then
   * generated lazily on first view).
   *
   * @param source metadata of the copied attachment
   * @param copyId identifier of the copy
   * @param copyOwnerId owner of the copy
   */
  void copyVideoPreview(FileMetadata source, String copyId, String copyOwnerId);
}
