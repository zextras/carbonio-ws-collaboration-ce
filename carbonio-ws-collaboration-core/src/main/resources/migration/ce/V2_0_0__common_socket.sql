-- The 1.x tables move untouched, with their data, constraints and indexes, to schema CHATS_V1: a rollback to 1.x
-- moves them back. 2.x never reads or writes CHATS_V1.
CREATE SCHEMA CHATS_V1;
ALTER TABLE CHATS.CHATS_USER SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.ROOM SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.SUBSCRIPTION SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.ROOM_USER_SETTINGS SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.FILE_METADATA SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.MEETING SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.PARTICIPANT SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.VIDEOSERVER_MEETING SET SCHEMA CHATS_V1;
ALTER TABLE CHATS.VIDEOSERVER_SESSION SET SCHEMA CHATS_V1;

-- 1.x times were stored as wall clock of the service JVM zone: the 2.x tables hold them as TIMESTAMPTZ, converted
-- with that zone.
CREATE TABLE CHATS.CHATS_USER
(
    ID             VARCHAR(64)  NOT NULL,
    STATUS_MESSAGE VARCHAR(256) NOT NULL DEFAULT '',
    CREATED_AT     TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT     TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT CHATS_USER_PKEY PRIMARY KEY (ID)
);

CREATE TABLE CHATS.ROOM
(
    ID                 VARCHAR(64) NOT NULL,
    NAME               VARCHAR(128),
    DESCRIPTION        VARCHAR(256),
    TYPE               VARCHAR(32) NOT NULL,
    MEETING_ID         VARCHAR(64),
    PICTURE_UPDATED_AT TIMESTAMPTZ,
    CREATED_AT         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT ROOM_PKEY PRIMARY KEY (ID)
);

CREATE TABLE CHATS.SUBSCRIPTION
(
    USER_ID    VARCHAR(64) NOT NULL,
    ROOM_ID    VARCHAR(64) NOT NULL,
    OWNER      BOOLEAN              DEFAULT FALSE,
    TEMPORARY  BOOLEAN              DEFAULT FALSE,
    EXTERNAL   BOOLEAN              DEFAULT FALSE,
    JOINED_AT  TIMESTAMPTZ          DEFAULT clock_timestamp(),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT SUBSCRIPTION_PKEY PRIMARY KEY (USER_ID, ROOM_ID)
);

CREATE TABLE CHATS.ROOM_USER_SETTINGS
(
    USER_ID     VARCHAR(64) NOT NULL,
    ROOM_ID     VARCHAR(64) NOT NULL,
    MUTED_UNTIL TIMESTAMPTZ,
    CLEARED_AT  TIMESTAMPTZ,
    CREATED_AT  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT ROOM_USER_SETTINGS_PKEY PRIMARY KEY (USER_ID, ROOM_ID)
);

CREATE TABLE CHATS.FILE_METADATA
(
    ID              VARCHAR(64)  NOT NULL,
    NAME            VARCHAR(256) NOT NULL,
    ORIGINAL_SIZE   INTEGER      NOT NULL,
    MIME_TYPE       VARCHAR(256) NOT NULL,
    TYPE            VARCHAR(32)  NOT NULL,
    USER_ID         VARCHAR(64)  NOT NULL,
    ROOM_ID         VARCHAR(64),
    AREA            VARCHAR(64),
    CHAT_MESSAGE_ID VARCHAR(64),
    CREATED_AT      TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT      TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT FILE_METADATA_PKEY PRIMARY KEY (ID)
);

CREATE TABLE CHATS.MEETING
(
    ID           VARCHAR(64) NOT NULL,
    NAME         VARCHAR(128),
    MEETING_TYPE VARCHAR(32) NOT NULL DEFAULT 'PERMANENT',
    ROOM_ID      VARCHAR(64) NOT NULL,
    ACTIVE       BOOLEAN              DEFAULT FALSE,
    CREATED_AT   TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    STARTED_AT   TIMESTAMPTZ,
    EXPIRATION   TIMESTAMPTZ,

    CONSTRAINT MEETING_PKEY PRIMARY KEY (ID)
);

CREATE TABLE CHATS.PARTICIPANT
(
    MEETING_ID       VARCHAR(64) NOT NULL,
    USER_ID          VARCHAR(64) NOT NULL,
    QUEUE_ID         VARCHAR(64),
    VIDEO_STREAM_ON  BOOLEAN              DEFAULT FALSE,
    AUDIO_STREAM_ON  BOOLEAN              DEFAULT FALSE,
    SCREEN_STREAM_ON BOOLEAN              DEFAULT FALSE,
    HAND_RAISED_AT   TIMESTAMPTZ,
    CREATED_AT       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UPDATED_AT       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT PARTICIPANT_PKEY PRIMARY KEY (MEETING_ID, USER_ID)
);

CREATE TABLE CHATS.VIDEOSERVER_MEETING
(
    MEETING_ID      VARCHAR(64) NOT NULL,
    CONNECTION_ID   VARCHAR(64) NOT NULL,
    AUDIO_HANDLE_ID VARCHAR(64) NOT NULL,
    VIDEO_HANDLE_ID VARCHAR(64) NOT NULL,
    AUDIO_ROOM_ID   VARCHAR(64) NOT NULL,
    VIDEO_ROOM_ID   VARCHAR(64) NOT NULL,

    CONSTRAINT VIDEOSERVER_MEETING_PKEY PRIMARY KEY (MEETING_ID)
);

CREATE TABLE CHATS.VIDEOSERVER_SESSION
(
    MEETING_ID          VARCHAR(64) NOT NULL,
    USER_ID             VARCHAR(64) NOT NULL,
    CONNECTION_ID       VARCHAR(64) NOT NULL,
    QUEUE_ID            VARCHAR(64),
    AUDIO_HANDLE_ID     VARCHAR(64),
    VIDEOOUT_HANDLE_ID  VARCHAR(64),
    VIDEOIN_HANDLE_ID   VARCHAR(64),
    SCREEN_HANDLE_ID    VARCHAR(64),
    VIDEO_OUT_STREAM_ON BOOLEAN DEFAULT FALSE,
    VIDEO_IN_STREAM_ON  BOOLEAN DEFAULT FALSE,
    SCREEN_STREAM_ON    BOOLEAN DEFAULT FALSE,
    AUDIO_STREAM_ON     BOOLEAN DEFAULT FALSE,

    CONSTRAINT VIDEOSERVER_SESSION_PKEY PRIMARY KEY (MEETING_ID, USER_ID)
);

