ALTER TABLE CHATS.ROOM RENAME COLUMN CREATED_AT TO CREATED_AT_V1;
ALTER TABLE CHATS.ROOM RENAME COLUMN UPDATED_AT TO UPDATED_AT_V1;
ALTER TABLE CHATS.ROOM
    ALTER COLUMN CREATED_AT_V1 DROP NOT NULL,
    ALTER COLUMN UPDATED_AT_V1 DROP NOT NULL,
    ADD COLUMN PICTURE_UPDATED_AT TIMESTAMPTZ,
    ADD COLUMN CREATED_AT TIMESTAMPTZ,
    ADD COLUMN UPDATED_AT TIMESTAMPTZ;
UPDATE CHATS.ROOM
SET PICTURE_UPDATED_AT = PICTURE_UPDATED_AT_V1 AT TIME ZONE ${jvm_zone},
    CREATED_AT         = CREATED_AT_V1 AT TIME ZONE ${jvm_zone},
    UPDATED_AT         = UPDATED_AT_V1 AT TIME ZONE ${jvm_zone};
ALTER TABLE CHATS.ROOM
