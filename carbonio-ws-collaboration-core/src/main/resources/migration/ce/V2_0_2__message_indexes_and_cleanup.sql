CREATE EXTENSION IF NOT EXISTS pg_trgm SCHEMA chats;

-- Foreign keys of the tables written by the import are validated once here instead of row by row.
ALTER TABLE CHATS.MESSAGE ADD CONSTRAINT FK_MESSAGE_ROOM FOREIGN KEY (ROOM_ID) REFERENCES CHATS.ROOM (ID) ON DELETE CASCADE;
ALTER TABLE CHATS.MESSAGE ADD CONSTRAINT FK_MESSAGE_REPLY FOREIGN KEY (REPLY_TO_ID) REFERENCES CHATS.MESSAGE (ID) ON DELETE SET NULL;
ALTER TABLE CHATS.SYSTEM_EVENT ADD CONSTRAINT FK_SYSTEM_EVENT_ROOM FOREIGN KEY (ROOM_ID) REFERENCES CHATS.ROOM (ID) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS MESSAGE_ROOM_CREATED_ID_ASC_IDX ON CHATS.MESSAGE (ROOM_ID, CREATED_AT, ID);
CREATE INDEX IF NOT EXISTS MESSAGE_ROOM_CREATED_IDX        ON CHATS.MESSAGE (ROOM_ID, CREATED_AT DESC);
CREATE INDEX IF NOT EXISTS MESSAGE_TEXT_TRGM_IDX           ON CHATS.MESSAGE USING GIN (TEXT gin_trgm_ops);

-- BUG-17: secondary indexes for ON DELETE cascade chains and startup cleanup
CREATE INDEX IF NOT EXISTS MESSAGE_REPLY_TO_ID_IDX  ON CHATS.MESSAGE      (REPLY_TO_ID) WHERE REPLY_TO_ID IS NOT NULL;

CREATE INDEX IF NOT EXISTS READ_MARKER_ROOM_ID_IDX         ON CHATS.READ_MARKER (ROOM_ID);
CREATE INDEX IF NOT EXISTS MESSAGE_PIN_MESSAGE_IDX          ON CHATS.MESSAGE_PIN  (MESSAGE_ID);
CREATE INDEX IF NOT EXISTS SYSTEM_EVENT_ROOM_CREATED_ID_IDX ON CHATS.SYSTEM_EVENT (ROOM_ID, CREATED_AT, ID);
CREATE INDEX IF NOT EXISTS USER_CONTACT_CONTACT_IDX         ON CHATS.USER_CONTACT (CONTACT_ID);

